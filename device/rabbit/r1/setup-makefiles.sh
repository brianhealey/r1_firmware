# Generates the Android.mk files that map each entry in proprietary-files.txt
# into the vendor image. Standard LineageOS/AOSP pattern.
#
# Usage: ./setup-makefiles.sh   (run from device/rabbit/r1)

set -e

MY_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

if [ ! -f "$MY_DIR/proprietary-files.txt" ]; then
    echo "proprietary-files.txt not found" >&2
    exit 1
fi

echo "# Auto-generated by setup-makefiles.sh — do not edit." > "$MY_DIR/Android.mk"

while IFS= read -r line; do
    # Skip comments and blank lines.
    case "$line" in
        ""|\#*) continue ;;
    esac

    # Skip the TBD section markers (lines that are not real paths).
    case "$line" in
        *TBD*|*---*) continue ;;
    esac

    # Map "lib/foo.so" -> vendor/lib/foo.so, "bin/foo" -> vendor/bin/foo, etc.
    # MediaTek blobs live under vendor/ (or system_ext/ for the radio-ex HALs).
    case "$line" in
        system_ext/*)
            dest="${line#system_ext/}"
            echo "PRODUCT_COPY_FILES += \\" >> "$MY_DIR/Android.mk"
            echo "    vendor/rabbit/r1/proprietary/system_ext/$dest:system/system_ext/$dest" >> "$MY_DIR/Android.mk"
            ;;
        *)
            echo "PRODUCT_COPY_FILES += \\" >> "$MY_DIR/Android.mk"
            echo "    vendor/rabbit/r1/proprietary/$line:system/vendor/$line" >> "$MY_DIR/Android.mk"
            ;;
    esac
done < "$MY_DIR/proprietary-files.txt"

echo "Wrote $MY_DIR/Android.mk"